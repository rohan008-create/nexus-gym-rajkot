const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const baseUrl = process.env.ARMORY_TEST_URL || 'http://127.0.0.1:3000';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const errors = [];
  const open = async (mobile = false) => {
    const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 }, isMobile: mobile, hasTouch: mobile });
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
    await page.goto(`${baseUrl}/hero`);
    await page.waitForSelector('[data-rope-status=ready]', { timeout: 90000 });
    return page;
  };
  try {
    fs.mkdirSync('qa', { recursive: true });
    const page = await open();
    assert.equal(await page.locator('#advantage').evaluate(el => el.previousElementSibling.id), 'armory');
    assert.equal(await page.locator('.advantage-button').count(), 4);
    assert.equal(await page.locator('.armory-is-pinned').count(), 1);
    const top = await page.locator('#advantage').evaluate(el => el.getBoundingClientRect().top + scrollY);
    const seek = async offset => { await page.evaluate(y => scrollTo(0, y), top + offset); await page.waitForTimeout(950); };
    await seek(-620);
    const darkness = await page.locator('.advantage-darkness').evaluate(el => +getComputedStyle(el).opacity);
    await seek(-300);
    assert.ok(await page.locator('.advantage-scanner').evaluate(el => +getComputedStyle(el).opacity) > .01, 'scanner crosses image');
    await seek(-84);
    const image = page.locator('.advantage-athlete');
    assert.ok(await image.evaluate(async el => { await el.decode(); return el.naturalWidth > 0; }));
    assert.ok(await page.locator('.advantage-darkness').evaluate(el => +getComputedStyle(el).opacity) < darkness, 'athlete reveals');
    const buttons = page.locator('.advantage-button');
    assert.equal(await buttons.nth(0).getAttribute('aria-expanded'), 'true');
    await buttons.nth(1).hover();
    assert.equal(await buttons.nth(1).getAttribute('aria-expanded'), 'true');
    await page.mouse.move(20, 120);
    assert.equal(await buttons.nth(0).getAttribute('aria-expanded'), 'true', 'hover restores selection');
    await buttons.nth(2).click();
    await page.mouse.move(20, 120);
    assert.equal(await buttons.nth(2).getAttribute('aria-expanded'), 'true', 'click persists');
    await buttons.nth(3).focus(); await page.keyboard.press('Enter');
    assert.equal(await buttons.nth(3).getAttribute('aria-expanded'), 'true', 'keyboard activation');
    await page.waitForTimeout(450);
    await page.screenshot({ path: 'qa/advantage-desktop.png' });
    await seek(-620);
    assert.ok(await page.locator('.advantage-darkness').evaluate(el => +getComputedStyle(el).opacity) > .3, 'reverse restores silhouette');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.advantage-darkness')).opacity === '0');
    assert.equal(await page.locator('.advantage-darkness').evaluate(el => +getComputedStyle(el).opacity), 0);
    assert.equal(await page.locator('.advantage-item').evaluateAll(els => els.every(el => +getComputedStyle(el).opacity === 1)), true);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.close();
    const mobile = await open(true);
    await mobile.locator('.advantage-button').nth(3).scrollIntoViewIfNeeded();
    await mobile.locator('.advantage-button').nth(3).tap();
    assert.equal(await mobile.locator('.advantage-button').nth(3).getAttribute('aria-expanded'), 'true');
    assert.ok(await mobile.locator('.advantage-athlete').evaluate(async el => { await el.decode(); return el.currentSrc.includes('-mobile.webp'); }));
    assert.equal(await mobile.locator('.armory-is-pinned').count(), 0);
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await mobile.locator('#advantage').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 80));
    await mobile.waitForTimeout(950);
    await mobile.screenshot({ path: 'qa/advantage-mobile.png', fullPage: false });
    assert.deepEqual(errors, []);
    fs.writeFileSync('qa/advantage-result.json', JSON.stringify({ passed: true, checks: ['placement', 'image decode', 'scanner', 'reversible reveal', 'hover preview', 'persistent click', 'keyboard', 'touch selection', 'responsive crop', 'reduced motion', 'Armory pin retained', 'no overflow'], errors }, null, 2));
    console.log('Advantage browser checks passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

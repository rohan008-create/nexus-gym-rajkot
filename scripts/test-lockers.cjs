const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.ARMORY_TEST_URL || 'http://127.0.0.1:3001';
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--enable-webgl', '--use-angle=d3d11'] });
  const errors = [];
  const open = async mobile => {
    const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: !!mobile, hasTouch: !!mobile });
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto(`${base}/hero`);
    await page.waitForSelector('[data-rope-status=ready]', { timeout: 90000 });
    await page.locator('#membership').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 84));
    await page.waitForSelector('[data-locker-status=ready]', { timeout: 45000 });
    await page.waitForTimeout(1000);
    return page;
  };
  const settled = async (page, id) => { await page.waitForSelector(`#membership[data-selected-plan=${id}][data-revealed=true]`, { timeout: 15000 }); };
  try {
    fs.mkdirSync('qa', { recursive: true });
    const p = await open(false);
    assert.equal(await p.locator('#membership').evaluate(el => el.previousElementSibling.id), 'trainers');
    assert.equal(await p.locator('#membership canvas').count(), 1);
    assert.equal(await p.locator('#membership').getAttribute('data-selected-plan'), 'none');
    assert.equal(await p.locator('.locker-mounted-display').count(), 0, 'closed doors hide HTML interiors');
    assert.equal(await p.locator('.locker-atmosphere').evaluate(el => getComputedStyle(el).backgroundImage.includes('url(')), false);
    await p.screenshot({ path: 'qa/lockers-closed.png' });
    // Center-door raycast interaction, rather than HTML-only selection.
    const box = await p.locator('#membership canvas').boundingBox();
    await p.mouse.click(box.x + box.width * .5, box.y + box.height * .52);
    await settled(p, 'pro');
    await p.screenshot({ path: 'qa/lockers-pro-open.png' });
    const mounted = p.locator('.locker-mounted-display');
    assert.equal(await mounted.count(), 1, 'one fitted interior display');
    assert.ok(await mounted.isVisible(), 'display is visible through open door');
    assert.ok(await mounted.evaluate(el => el.scrollHeight <= el.clientHeight && el.scrollWidth <= el.clientWidth), 'interior copy fits its physical panel');
    const panelBounds = await mounted.boundingBox();
    assert.ok(panelBounds.x >= box.x && panelBounds.x + panelBounds.width <= box.x + box.width, 'interior stays within scene');
    await p.getByRole('button', { name: 'Enquire about Pro membership inside locker' }).click();
    assert.ok((await p.locator('.trial-membership-plan').innerText()).includes('Pro'), 'mounted CTA preserves its own plan');
    await p.getByRole('button', { name: 'Close trial enquiry' }).click();
    assert.equal(await p.locator('.membership-panel').count(), 1);
    await p.getByRole('button', { name: '01 Basic', exact: false }).click();
    await settled(p, 'basic');
    await p.getByRole('button', { name: '03 Elite', exact: false }).click();
    await p.getByRole('button', { name: '02 Pro', exact: false }).click();
    await p.getByRole('button', { name: '03 Elite', exact: false }).click();
    await settled(p, 'elite');
    assert.equal(await p.locator('.locker-mounted-display').count(), 1, 'rapid switching does not overlap interior displays');
    assert.ok((await p.locator('.membership-panel').innerText()).includes('ELITE'));
    await p.getByRole('button', { name: 'JOIN NOW', exact: true }).click();
    await p.locator('.trial-dialog').waitFor({ state: 'visible' });
    assert.ok((await p.locator('.trial-membership-plan').innerText()).includes('Elite'));
    await p.getByLabel('Your name').fill('Preview Member');
    await p.getByRole('button', { name: 'Prepare enquiry' }).click();
    assert.ok((await p.locator('.enquiry-result pre').innerText()).includes('Selected plan: Elite'));
    assert.ok(!(await p.locator('.enquiry-result pre').innerText()).includes('a free trial'));
    await p.getByRole('button', { name: 'Close trial enquiry' }).click();
    await p.getByRole('button', { name: 'Close locker', exact: true }).click();
    assert.equal(await p.locator('#membership').getAttribute('data-selected-plan'), 'none');
    // Closing the plan enquiry restores the existing trial flow.
    await p.getByRole('button', { name: 'Book Free Trial', exact: true }).click();
    assert.equal(await p.locator('.trial-membership-plan').count(), 0);
    await p.getByRole('button', { name: 'Close trial enquiry' }).click();
    await p.emulateMedia({ reducedMotion: 'reduce' });
    const basic = p.getByRole('button', { name: '01 Basic', exact: false }); await basic.focus(); await p.keyboard.press('Enter'); await settled(p, 'basic');
    assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await p.setViewportSize({ width: 768, height: 1024 });
    await p.locator('#membership').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 84));
    await p.waitForTimeout(1000);
    await p.screenshot({ path: 'qa/lockers-tablet.png' });
    assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await p.close();
    const m = await open(true);
    assert.equal(await m.locator('#membership canvas').count(), 1);
    await m.getByRole('button', { name: 'OPEN LOCKER', exact: true }).tap(); await settled(m, 'pro');
    await m.getByRole('button', { name: '03 Elite', exact: false }).tap();
    assert.equal(await m.locator('#membership').getAttribute('data-selected-plan'), 'none');
    await m.getByRole('button', { name: 'OPEN LOCKER', exact: true }).tap(); await settled(m, 'elite');
    await m.locator('#membership').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 80)); await m.waitForTimeout(900);
    await m.screenshot({ path: 'qa/lockers-mobile-open.png' });
    assert.ok(await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await m.setViewportSize({ width: 320, height: 844 });
    await m.waitForTimeout(950);
    await m.screenshot({ path: 'qa/lockers-small-mobile.png' });
    assert.ok(await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    // Context loss should preserve the HTML plan selector and enquiry action.
    await m.locator('#membership canvas').evaluate(canvas => canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
    await m.waitForSelector('[data-locker-status=error]');
    assert.ok(await m.getByRole('button', { name: 'JOIN NOW', exact: true }).isVisible());
    await m.getByRole('button', { name: 'JOIN NOW', exact: true }).tap();
    assert.ok(await m.locator('.trial-dialog').isVisible());
    assert.deepEqual(errors, []);
    fs.writeFileSync('qa/lockers-result.json', JSON.stringify({ passed: true, checks: ['section order', 'single renderer', 'CSS background', 'initial closed state', 'raycast door selection', 'physical opening settled', 'fitted HTML display', 'interior content fits', 'mounted enquiry CTA', 'no overlapping displays', 'all plans', 'rapid switching', 'one panel', 'selected-plan enquiry', 'trial flow preserved', 'keyboard', 'reduced motion', 'mobile selection', 'mobile door open', '320px framing', 'WebGL fallback', 'no overflow', 'no runtime errors'], errors }, null, 2));
    console.log('Locker browser checks passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });

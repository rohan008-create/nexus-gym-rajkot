const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.ARMORY_TEST_URL || 'http://127.0.0.1:3000';
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--enable-webgl', '--use-angle=d3d11'] });
 const errors = [];
 const open = async mobile => { const p = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: !!mobile, hasTouch: !!mobile }); p.on('pageerror', e => errors.push(e.message)); p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); }); p.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); }); await p.goto(`${base}/hero`); await p.waitForSelector('#home[data-tour-status=ready]', { timeout: 90000 }); await p.locator('#trainers').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 84)); return p; };
 try {
  fs.mkdirSync('qa', { recursive: true });
  const p = await open(false);
  assert.equal(await p.locator('#trainers').evaluate(el => el.previousElementSibling.id), 'advantage');
  await p.waitForFunction(() => document.querySelectorAll('.trainer-installation[data-status=ready]').length === 5, { timeout: 30000 });
  assert.equal(await p.locator('#trainers canvas').count(), 1, 'all five badges share one depth-tested canvas');
  await p.waitForTimeout(4500);
  await p.screenshot({ path: 'qa/trainers-desktop.png' });
  const badge = p.locator('.trainer-installation').first(); const canvas = p.locator('#trainers canvas');
  const bounds = await badge.locator('.trainer-lanyard-slot').boundingBox();
  await p.mouse.click(bounds.x + bounds.width / 2, bounds.y + bounds.height * .54);
  await p.waitForTimeout(250);
  assert.equal(await badge.locator('.lanyard').getAttribute('data-face'), 'back', '3D click flips');
  await badge.getByRole('button').focus(); await p.keyboard.press('Enter');
  await p.waitForFunction(() => document.querySelector('.trainer-installation button').getAttribute('aria-pressed') === 'false');
  assert.equal(await badge.getByRole('button').getAttribute('aria-pressed'), 'false', 'keyboard flips front');
  await p.waitForTimeout(2000);
  const before = await badge.locator('.lanyard').getAttribute('data-face');
  await p.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height * .54); await p.mouse.down();
  await p.mouse.move(bounds.x + bounds.width / 2 + 60, bounds.y + bounds.height * .54 + 25, { steps: 12 });
  assert.equal(await badge.locator('.lanyard').getAttribute('data-interaction'), 'dragging');
  const held = await canvas.screenshot(); await p.mouse.up(); await p.waitForTimeout(650);
  assert.equal(await badge.locator('.lanyard').getAttribute('data-face'), before, 'drag does not flip');
  assert.equal(await badge.locator('.lanyard').getAttribute('data-interaction'), 'released');
  assert.notDeepEqual(await canvas.screenshot(), held, 'card moves after release');
  await p.getByRole('button', { name: '03 Demo Trainer 03' }).click();
  assert.ok((await p.locator('#trainer-profile').innerText()).toLowerCase().includes('performance & conditioning'));
  assert.equal(await p.locator('.armory-is-pinned').count(), 1);
  await p.emulateMedia({ reducedMotion: 'reduce' }); await p.waitForTimeout(300);
  assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await p.close();
  const m = await open(true);
  await m.waitForFunction(() => document.querySelectorAll('.trainer-installation[data-status=ready]').length === 1);
  assert.equal(await m.locator('#trainers canvas').count(), 1);
  await m.getByRole('button', { name: '02 Demo Trainer 02' }).tap();
  await m.waitForSelector('[data-trainer=trainer-02][data-status=ready]');
  assert.equal(await m.locator('#trainers canvas').count(), 1);
  await m.getByRole('button', { name: 'Flip Demo Trainer 02 badge' }).tap();
  await m.waitForFunction(() => document.querySelector('[aria-label="Flip Demo Trainer 02 badge"]').getAttribute('aria-pressed') === 'true');
  assert.equal(await m.getByRole('button', { name: 'Flip Demo Trainer 02 badge' }).getAttribute('aria-pressed'), 'true');
  await m.locator('#trainers').evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY - 80)); await m.waitForTimeout(4000);
  await m.screenshot({ path: 'qa/trainers-mobile.png' });
  const mobileCanvas = await m.locator('#trainers canvas').boundingBox();
  const touchX = mobileCanvas.x + mobileCanvas.width / 2, touchY = mobileCanvas.y + mobileCanvas.height * .5;
  await m.touchscreen.tap(touchX, touchY);
  await m.waitForFunction(() => document.querySelector('.trainer-installation button').getAttribute('aria-pressed') === 'false');
  await m.waitForTimeout(2200);
  const cdp = await m.context().newCDPSession(m);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchX, y: touchY }] });
  for (let step = 1; step <= 6; step++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchX + step * 5, y: touchY + step * 2 }] });
  assert.equal(await m.locator('.lanyard').getAttribute('data-interaction'), 'dragging', 'touch dragging works');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.equal(await m.locator('.lanyard').getAttribute('data-face'), 'front', 'touch drag does not flip');
  const y = await m.evaluate(() => scrollY); await m.mouse.wheel(0, 300); await m.waitForTimeout(400); assert.ok(await m.evaluate(() => scrollY) > y, 'page remains scrollable');
  assert.ok(await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  fs.writeFileSync('qa/trainers-result.json', JSON.stringify({ passed: true, checks: ['placement', 'five desktop canvases and shared rail', 'real textures', 'pointer flip', 'keyboard flip', 'drag', 'no drag flip', 'release motion', 'HTML profile selection', 'one mobile canvas', 'mobile switching', 'mobile flip', 'touch tap-to-flip', 'touch dragging', 'no touch drag flip', 'normal scrolling', 'reduced motion', 'Armory pin', 'no overflow'], errors }, null, 2));
  console.log('Trainer browser checks passed.');
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });

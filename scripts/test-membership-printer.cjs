const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.MEMBERSHIP_TEST_URL || 'http://127.0.0.1:3001';

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--enable-webgl', '--use-angle=d3d11'] });
  const errors = [], checks = [];
  fs.mkdirSync('qa', { recursive: true });
  async function open(mobile = false, reduced = false, audioUnavailable = false) {
    const page = await browser.newPage({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, isMobile: mobile, hasTouch: mobile, reducedMotion: reduced ? 'reduce' : 'no-preference' });
    page.on('pageerror', error => errors.push(error.message));
    if (audioUnavailable) await page.addInitScript(() => { window.AudioContext = undefined; });
    await page.goto(`${base}/hero`, { timeout: 90000 });
    await page.locator('#membership').waitFor({ timeout: 60000 });
    await page.locator('#membership').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + scrollY - 85));
    await page.waitForTimeout(500);
    return page;
  }
  const printer = page => page.locator('.receipt-printer');
  const print = page => page.getByRole('button', { name: 'Print receipt', exact: true });
  const receipt = page => page.getByRole('button', { name: 'Receipt. Pull it, or press Enter, to tear it off.', exact: true });
  const stopped = page => page.locator('.receipt-printer[data-printer-phase=stopped]').waitFor({ timeout: 10000 });
  try {
    const page = await open();
    assert.equal(await page.locator('.nexus-vault-section').count(), 0);
    assert.equal(await page.locator('#membership canvas').count(), 0);
    assert.equal(await page.locator('#membership').evaluate(el => el.previousElementSibling.id), 'trainers');
    assert.equal(await page.locator('#membership').getAttribute('data-selected-plan'), 'pro');
    await page.locator('#membership').screenshot({ path: 'qa/membership-printer-desktop-idle.png' });
    await print(page).click();
    await page.locator('.receipt-printer[data-printer-phase=printing]').waitFor();
    await page.waitForTimeout(350);
    const partial = (await receipt(page).boundingBox()).height;
    await page.waitForTimeout(450);
    assert.ok((await receipt(page).boundingBox()).height > partial + 2, 'paper feeds out of slot');
    await print(page).click(); await stopped(page);
    const height = (await receipt(page).boundingBox()).height;
    await page.waitForTimeout(200);
    assert.ok(Math.abs((await receipt(page).boundingBox()).height - height) < 1, 'stop holds paper');
    await print(page).click(); await stopped(page);
    assert.equal(await printer(page).getAttribute('data-receipt-count'), '2');
    await receipt(page).focus(); await page.keyboard.press('Enter');
    await page.locator('.receipt-printer[data-receipt-count="0"]').waitFor();
    await page.locator('[data-flying-receipt]').waitFor({ state: 'detached' });
    checks.push('vault replaced; animated feed, stop, repeat and keyboard tear');

    await page.locator('.membership-print-plans button').nth(0).click();
    await print(page).click(); await stopped(page);
    assert.ok((await receipt(page).innerText()).includes('BASIC'));
    await page.locator('.membership-print-plans button').nth(2).click();
    assert.ok((await receipt(page).innerText()).includes('BASIC'), 'old slip keeps its plan');
    assert.ok(!(await receipt(page).innerText()).includes('ELITE'), 'selection does not rewrite printed paper');
    await print(page).click(); await stopped(page);
    const text = await receipt(page).innerText();
    assert.ok(text.includes('BASIC') && text.includes('ELITE'));
    assert.ok(text.includes('Confirm with Nexus') && text.includes('NOT A PAYMENT RECEIPT'));
    assert.ok(!text.includes('Subtotal') && !text.includes('Cola'));
    await page.locator('#membership').screenshot({ path: 'qa/membership-printer-desktop-printed.png' });
    await page.getByRole('button', { name: 'ENQUIRE ABOUT ELITE', exact: true }).click();
    await page.locator('.trial-dialog').waitFor({ state: 'visible' });
    assert.ok((await page.locator('.trial-membership-plan').innerText()).includes('Elite'));
    await page.getByLabel('Your name').fill('Printer Preview');
    await page.getByRole('button', { name: 'Prepare enquiry', exact: true }).click();
    assert.ok((await page.locator('.enquiry-result pre').innerText()).includes('Selected plan: Elite'));
    await page.getByRole('button', { name: 'Close trial enquiry', exact: true }).click();
    checks.push('immutable plan snapshots, honest pricing and selected-plan enquiry');

    await receipt(page).scrollIntoViewIfNeeded();
    const box = await receipt(page).boundingBox();
    // Pull visible paper below the fixed navbar, rather than its clipped top.
    const x = box.x + box.width / 2, y = Math.max(150, Math.min(900, box.y + box.height - 65));
    assert.ok(await page.evaluate(({ x, y }) => !!document.elementFromPoint(x, y)?.closest('[aria-label^="Receipt."]'), { x, y }), 'pointer starts on visible paper');
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 100, y - 35, { steps: 8 }); await page.mouse.up();
    await page.locator('.receipt-printer[data-receipt-count="0"]').waitFor();
    await page.getByRole('button', { name: 'Turn sound off', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Turn sound on', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.locator('.site-nav').getByRole('link', { name: 'Plans', exact: true }).click();
    await page.waitForTimeout(1200);
    assert.ok(Math.abs(await page.locator('#membership').evaluate(el => el.getBoundingClientRect().top) - 80) < 30, 'Plans navigation targets new section');
    checks.push('pointer tear, mute and Plans navigation');
    await page.close();

    const mobile = await open(true, true, true);
    await mobile.locator('.membership-print-plans button').nth(2).tap();
    await print(mobile).tap(); await stopped(mobile);
    assert.ok((await receipt(mobile).innerText()).includes('ELITE'));
    await mobile.locator('.membership-printer-stage').screenshot({ path: 'qa/membership-printer-mobile.png' });
    await mobile.setViewportSize({ width: 320, height: 740 });
    await mobile.waitForTimeout(300);
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px no horizontal overflow');
    const stage = await mobile.locator('.membership-printer-stage').boundingBox();
    const button = await print(mobile).boundingBox();
    assert.ok(button.x >= stage.x && button.x + button.width <= stage.x + stage.width, 'scaled PRINT button fits');
    await receipt(mobile).scrollIntoViewIfNeeded();
    const mb = await receipt(mobile).boundingBox(), tx = mb.x + mb.width / 2, ty = Math.max(150, Math.min(650, mb.y + mb.height - 50));
    const cdp = await mobile.context().newCDPSession(mobile);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: tx, y: ty }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: tx + 100, y: ty - 20 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await mobile.locator('.receipt-printer[data-receipt-count="0"]').waitFor();
    await mobile.locator('.membership-print-plans button').nth(0).focus(); await mobile.keyboard.press('Enter');
    await print(mobile).focus(); await mobile.keyboard.press('Enter'); await stopped(mobile);
    assert.ok((await receipt(mobile).innerText()).includes('BASIC'));
    await receipt(mobile).focus(); await mobile.keyboard.press('Space');
    await mobile.locator('.receipt-printer[data-receipt-count="0"]').waitFor();
    await mobile.close();
    checks.push('mobile touch print/tear, 320px resize, keyboard, reduced motion, unavailable audio');
    assert.deepEqual(errors, []);
    fs.writeFileSync('qa/membership-printer-result.json', JSON.stringify({ passed: true, checks, errors }, null, 2));
    console.log('VERDICT: PASS');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); console.log(`VERDICT: FAIL -- ${error.message}`); process.exitCode = 1; });

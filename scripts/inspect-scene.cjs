const { chromium } = require('playwright');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('response', response => { if (response.status() >= 400) console.log('HTTP error', response.status(), response.url()); });
  const response = await page.goto('http://127.0.0.1:3000');
  await page.waitForSelector('canvas');
  await page.waitForTimeout(7000);
  fs.mkdirSync('qa', { recursive: true });
  await page.screenshot({ path: 'qa/desktop.png' });
  await page.mouse.move(650, 470); await page.mouse.down(); await page.mouse.move(1120, 480, { steps: 30 }); await page.mouse.up(); await page.waitForTimeout(1000);
  await page.screenshot({ path: 'qa/orbit.png' });
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(2000);
  await page.screenshot({ path: 'qa/mobile.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.waitForTimeout(1000);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto('http://127.0.0.1:3000'); await mobile.waitForSelector('canvas'); await mobile.waitForTimeout(3000);
  const touch = await mobile.context().newCDPSession(mobile);
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 130, y: 420 }] });
  for (let i = 0; i < 10; i++) await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 130 + i * 12, y: 420 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 140, y: 400 }, { x: 240, y: 400 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 110, y: 400 }, { x: 270, y: 400 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await mobile.waitForTimeout(1500); await mobile.screenshot({ path: 'qa/touch.png' });
  const result = { status: response.status(), canvas: await page.locator('canvas').count(), errors };
  fs.writeFileSync('qa/result.json', JSON.stringify(result, null, 2)); console.log(result);
  await browser.close();
  if (errors.length) process.exitCode = 1;
})();
